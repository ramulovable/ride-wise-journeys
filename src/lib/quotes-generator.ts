function generated(cat: QuoteCategory): Quote[] {
  const p = PARTS[cat];
  if (!p) return [];
  const out: Quote[] = [];
  p.a.forEach((a, i) => p.b.forEach((b, j) => out.push({ id: `g-${cat}-${i}-${j}`, cat, text: `${a} ${b}`.replace(" \n", "\n") })));
  return out;
}

const POOLS = new Map<QuoteCategory, Quote[]>();
export function poolFor(cat: QuoteCategory): Quote[] {
  if (cat === "today") {
    const cats: QuoteCategory[] = ["deen", "motivation", "emotional", "morning", "shayari"];
    return cats.flatMap(poolFor);
  }
  if (!POOLS.has(cat)) POOLS.set(cat, [...QUOTES.filter((q) => q.cat === cat), ...generated(cat)]);
  return POOLS.get(cat)!;
}

const KEY = "qs-seen-v1";
function readSeen(): Set<string> {
  try { return new Set(JSON.parse(localStorage.getItem(KEY) || "[]") as string[]); } catch { return new Set(); }
}
function writeSeen(s: Set<string>) {
  try { localStorage.setItem(KEY, JSON.stringify([...s].slice(-4000))); } catch { /* ignore */ }
}

/** Random unseen quotes; when a pool runs out, its history resets and the cycle starts again. */
export function nextQuotes(cat: QuoteCategory, count: number, exclude: Set<string> = new Set()): Quote[] {
  const pool = poolFor(cat);
  const seen = readSeen();
  let fresh = pool.filter((q) => !seen.has(q.id) && !exclude.has(q.id));
  if (fresh.length < count) {
    pool.forEach((q) => seen.delete(q.id));
    fresh = pool.filter((q) => !exclude.has(q.id));
  }
  const picked: Quote[] = [];
  while (picked.length < count && fresh.length) {
    const i = Math.floor(Math.random() * fresh.length);
    picked.push(fresh.splice(i, 1)[0]!);
  }
  picked.forEach((q) => seen.add(q.id));
  writeSeen(seen);
  return picked;
}
