function istToday(): Date {
  const now = new Date(Date.now() + 5.5 * 3600 * 1000);
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
}

function festivalDate(f: Festival, year: number): Date {
  const parts = f.date.split("-").map(Number);
  if (parts.length === 3) return new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]));
  return new Date(Date.UTC(year, parts[0] - 1, parts[1]));
}

/** Festivals from 2 days before through the day itself, plus the next upcoming ones. */
export function festivalState() {
  const today = istToday();
  const y = today.getUTCFullYear();
  const items = FESTIVALS.flatMap((f) =>
    f.date.length === 5 ? [{ f, d: festivalDate(f, y) }, { f, d: festivalDate(f, y + 1) }] : [{ f, d: festivalDate(f, y) }],
  )
    .map(({ f, d }) => ({ ...f, when: d, daysLeft: Math.round((d.getTime() - today.getTime()) / 86400000) }))
    .filter((x) => x.daysLeft >= 0)
    .sort((a, b) => a.daysLeft - b.daysLeft);
  return { active: items.filter((x) => x.daysLeft <= 2), upcoming: items.slice(0, 8) };
}

export function festivalQuotes(): Quote[] {
  const { upcoming } = festivalState();
  return upcoming.map((x, i) => ({
    id: `fest-${i}-${x.name}`,
    cat: "festival" as const,
    text: x.daysLeft === 0 ? x.wish : x.daysLeft <= 2 ? `आने वाले ${x.name} की अग्रिम शुभकामनाएं!\n${x.wish}` : x.wish,
    by: x.daysLeft === 0 ? `आज ${x.name}` : `${x.name} • ${x.daysLeft} दिन बाद`,
  }));
}

function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

/** Different set every day and per user. */
export function todaysPicks(seed: string, count = 6): Quote[] {
  const day = istToday().toISOString().slice(0, 10);
  const { active } = festivalState();
  const fest = festivalQuotes().slice(0, active.length);
  const pool = QUOTES.filter((q) => q.cat !== "birthday");
  const sorted = [...pool].sort((a, b) => hash(`${day}${seed}${a.id}`) - hash(`${day}${seed}${b.id}`));
  return [...fest, ...sorted.slice(0, count)];
}

export function shuffled(list: Quote[], seed: string) {
  return [...list].sort((a, b) => hash(seed + a.id) - hash(seed + b.id));
}
